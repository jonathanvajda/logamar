#!/usr/bin/env python3
"""Generate or check the offline asset list and its content-based cache version."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"


def build():
    paths = ["index.html", "data-sources.html", "manifest.webmanifest", "favicon.ico",
             "data/generated/greek.json", "data/generated/hebrew.json",
             "data/generated/data-manifest.json", "data/generated/hebrew-manifest.json",
             "data/generated/greek-frequency-report.json", "data/generated/hebrew-frequency-report.json"]
    paths += [path.relative_to(DOCS).as_posix() for pattern in ["js/*.js", "css/*.css", "icons/*"] for path in DOCS.glob(pattern)]
    paths = sorted(set(paths))
    digest = hashlib.sha256()
    # The SW itself affects the version but is not fetched through its own cache.
    for path in ["sw.js", *paths]:
        digest.update(path.encode() + b"\0" + (DOCS / path).read_bytes() + b"\0")
    manifest = {"version": digest.hexdigest()[:20], "assets": ["./", *["./" + path for path in paths]]}
    return ("// Generated by tools/build_pwa.py; rebuild after changing app assets.\nself.LOGAMAR_PRECACHE = " + json.dumps(manifest, indent=2) + ";\n").encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = DOCS / "precache-manifest.js"
    content = build()
    if args.check:
        if not output.exists() or output.read_bytes() != content:
            parser.exit(1, "Offline asset list is stale. Run python tools/build_pwa.py\n")
        print("Offline asset list and cache version verified.")
    else:
        output.write_bytes(content)
        print("Generated offline asset list and content-based cache version.")


if __name__ == "__main__":
    main()
